from dataclasses import dataclass

from src.core.models import Bar, Fill, Order, OrderSide, Trade
from src.execution.simulator import ExecutionSimulator
from src.portfolio.portfolio import Portfolio
from src.strategies.base import Strategy
from src.portfolio.sizing import FixedQuantitySizer, PositionSizer

@dataclass
class BacktestResult:
    equity_curve: list[dict]
    orders: list[Order]
    fills: list[Fill]
    trades: list[Trade]


class BacktestEngine:
    def __init__(
        self,
        initial_cash: float,
        strategy: Strategy,
        position_sizer: PositionSizer | None = None,
        slippage_bps: float = 0.0,
        fee_bps: float = 0.0,
    ):
        self.portfolio = Portfolio(initial_cash=initial_cash)

        self.strategy = strategy

        self.position_sizer = (
            position_sizer
            if position_sizer is not None
            else FixedQuantitySizer(1)
        )

        self.execution = ExecutionSimulator(
            slippage_bps=slippage_bps,
            fee_bps=fee_bps,
        )

        self.pending_order: Order | None = None

        self.equity_curve = []
        self.orders = []
        self.fills = []
        self.trades = []

        self._open_trade = None

    def _record_fill(self, fill: Fill) -> None:
        self.fills.append(fill)

        if fill.side == OrderSide.BUY:
            if self._open_trade is not None:
                raise ValueError(
                    "Multiple simultaneous long trades are not supported."
                )

            self._open_trade = {
                "symbol": fill.symbol,
                "entry_time": fill.timestamp,
                "quantity": fill.quantity,
                "entry_price": fill.price,
                "entry_fee": fill.fee,
            }

        elif fill.side == OrderSide.SELL:
            if self._open_trade is None:
                raise ValueError(
                    "Cannot record a sell without an open trade."
                )

            if fill.quantity != self._open_trade["quantity"]:
                raise ValueError(
                    "Partial trade exits are not yet supported."
                )

            trade = Trade(
                symbol=self._open_trade["symbol"],
                entry_time=self._open_trade["entry_time"],
                exit_time=fill.timestamp,
                quantity=self._open_trade["quantity"],
                entry_price=self._open_trade["entry_price"],
                exit_price=fill.price,
                entry_fee=self._open_trade["entry_fee"],
                exit_fee=fill.fee,
            )

            self.trades.append(trade)
            self._open_trade = None

    def run(self, bars: list[Bar]) -> BacktestResult:
        if not bars:
            raise ValueError("Cannot run backtest with no bars.")

        for bar in bars:

            # -----------------------------------------------------
            # Execute the order generated by the previous bar.
            # Position sizing happens here because the execution
            # price is now known.
            # -----------------------------------------------------

            if self.pending_order is not None:
                pending_order = self.pending_order

                quantity = self.position_sizer.quantity(
                    portfolio=self.portfolio,
                    symbol=pending_order.symbol,
                    price=bar.open,
                    side=pending_order.side,
                )

                if quantity > 0:
                    sized_order = Order(
                        symbol=pending_order.symbol,
                        side=pending_order.side,
                        quantity=quantity,
                        order_type=pending_order.order_type,
                    )

                    fill = self.execution.execute(
                        sized_order,
                        bar,
                    )

                    self.portfolio.apply_fill(fill)
                    self._record_fill(fill)

                self.pending_order = None

            # -----------------------------------------------------
            # Mark portfolio to market using current close.
            # -----------------------------------------------------

            equity = self.portfolio.equity(
                {bar.symbol: bar.close}
            )

            self.equity_curve.append(
                {
                    "timestamp": bar.timestamp,
                    "equity": equity,
                    "cash": self.portfolio.cash,
                }
            )

            # -----------------------------------------------------
            # Generate a new signal/order from this bar.
            # It will execute on the NEXT bar.
            # -----------------------------------------------------

            order = self.strategy.on_bar(bar)

            if order is not None:
                self.pending_order = order
                self.orders.append(order)

        return BacktestResult(
            equity_curve=self.equity_curve,
            orders=self.orders,
            fills=self.fills,
            trades=self.trades,
        )